# 手の骨（スマホ版でも細かく残す）
HAND_BONES = {f"FMA{n}" for n in range(24450, 24473)}


def parts():
    """[{id, c, r, mid}] を付録Bの順で返す"""
    out = []
    for c, r, ids in TABLE:
        for tok in ids.split():
            mid = tok.endswith("*")
            tok = tok.rstrip("*")
            pid = tok if tok.startswith("BP") else f"FMA{tok}"
            out.append({"id": pid, "c": c, "r": r, "mid": mid})
    return out


